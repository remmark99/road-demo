-- Equipment monitoring: camera and controller outages.
--
-- Written by the backend's equipment-monitor service (bus_stop_analytics,
-- src/equipment_monitor) with the service role:
--   * cameras.last_seen_at   — heartbeat stamped by the frame grabber
--   * bus_stops.last_ok_at   — heartbeat stamped by the controller worker on a
--                              successful poll (last_ping_at stays "last attempt")
--   * equipment_outages      — one row per outage: what was down, from when to when
--   * equipment_state        — current status of every monitored device
--
-- Outage notifications themselves are ordinary rows in public.alerts
-- (alert_type camera_offline / camera_online) and public.controller_alerts
-- (category controller_offline / controller_online), so the existing insert
-- triggers deliver them by email / MAX with no change here.
--
-- Apply before deploying the backend version that writes these columns.
-- Additive and idempotent: existing tables only gain nullable columns.

BEGIN;

ALTER TABLE public.cameras
  ADD COLUMN IF NOT EXISTS last_seen_at TIMESTAMPTZ;
ALTER TABLE public.bus_stops
  ADD COLUMN IF NOT EXISTS last_ok_at TIMESTAMPTZ;

COMMENT ON COLUMN public.cameras.last_seen_at IS
  'Last time the frame grabber received frames from this camera (heartbeat, ~15 s).';
COMMENT ON COLUMN public.bus_stops.last_ok_at IS
  'Last successful poll of this stop''s controller. last_ping_at also moves on failures.';

-- ── Outage history ───────────────────────────────────────────────────────────
-- Point in time T:  started_at <= T AND (ended_at IS NULL OR ended_at > T)
-- A period:         started_at < "to" AND (ended_at IS NULL OR ended_at > "from")
-- No foreign keys on purpose: history must survive a stop or camera being
-- deleted, and a failed insert would stall the monitor's retry queue.

CREATE TABLE IF NOT EXISTS public.equipment_outages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  equipment_type TEXT NOT NULL CHECK (equipment_type IN ('camera', 'controller')),
  -- camera_index for cameras, bus_stops.id for controllers
  equipment_id INTEGER NOT NULL,
  bus_stop_id INTEGER,
  location_id TEXT,
  -- Last sighting before the device went dark.
  started_at TIMESTAMPTZ NOT NULL,
  -- When the monitor noticed (started_at + heartbeat staleness).
  detected_at TIMESTAMPTZ NOT NULL,
  ended_at TIMESTAMPTZ,
  -- recovered: the device came back; removed: it stopped being monitored.
  resolution TEXT CHECK (resolution IN ('recovered', 'removed')),
  -- Set once the outage was announced (it lasted EQUIPMENT_ALERT_AFTER_SEC).
  notified_at TIMESTAMPTZ,
  recovery_notified_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (ended_at IS NULL OR ended_at >= started_at),
  CHECK ((ended_at IS NULL) = (resolution IS NULL))
);

-- At most one open outage per device.
CREATE UNIQUE INDEX IF NOT EXISTS equipment_outages_one_open_per_device
  ON public.equipment_outages (equipment_type, equipment_id)
  WHERE ended_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_equipment_outages_started
  ON public.equipment_outages (started_at DESC);
CREATE INDEX IF NOT EXISTS idx_equipment_outages_ended
  ON public.equipment_outages (ended_at DESC);
CREATE INDEX IF NOT EXISTS idx_equipment_outages_device_time
  ON public.equipment_outages (equipment_type, equipment_id, started_at DESC);

COMMENT ON TABLE public.equipment_outages IS
  'Camera / controller outages. Open while ended_at IS NULL. Written by equipment-monitor.';

-- ── Current status ───────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.equipment_state (
  equipment_type TEXT NOT NULL CHECK (equipment_type IN ('camera', 'controller')),
  equipment_id INTEGER NOT NULL,
  bus_stop_id INTEGER,
  location_id TEXT,
  stop_name TEXT,
  -- unknown: no heartbeat has ever been written for the device.
  status TEXT NOT NULL CHECK (status IN ('online', 'offline', 'unknown')),
  -- Start of the current outage, or when the device last came back; NULL if unknown.
  status_since TIMESTAMPTZ,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (equipment_type, equipment_id)
);

COMMENT ON TABLE public.equipment_state IS
  'Every monitored camera / controller and its current status. Written by equipment-monitor.';

-- ── Access ───────────────────────────────────────────────────────────────────
-- Readable by signed-in users with the stops module (or admins), like the
-- lying-person episodes; written only by the backend's service role.

ALTER TABLE public.equipment_outages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.equipment_state ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Stop users read equipment outages" ON public.equipment_outages;
CREATE POLICY "Stop users read equipment outages"
  ON public.equipment_outages
  FOR SELECT
  TO authenticated
  USING (
    EXISTS (
      SELECT 1
        FROM public.profiles AS profile
       WHERE profile.id = auth.uid()
         AND (
           profile.role = 'admin'
           OR coalesce(to_jsonb(profile.modules), '[]'::jsonb) ? 'stops'
         )
    )
  );

DROP POLICY IF EXISTS "Stop users read equipment state" ON public.equipment_state;
CREATE POLICY "Stop users read equipment state"
  ON public.equipment_state
  FOR SELECT
  TO authenticated
  USING (
    EXISTS (
      SELECT 1
        FROM public.profiles AS profile
       WHERE profile.id = auth.uid()
         AND (
           profile.role = 'admin'
           OR coalesce(to_jsonb(profile.modules), '[]'::jsonb) ? 'stops'
         )
    )
  );

REVOKE ALL ON public.equipment_outages FROM anon, authenticated;
REVOKE ALL ON public.equipment_state FROM anon, authenticated;
GRANT SELECT ON public.equipment_outages TO authenticated;
GRANT SELECT ON public.equipment_state TO authenticated;
GRANT ALL ON public.equipment_outages TO service_role;
GRANT ALL ON public.equipment_state TO service_role;

DO $$
DECLARE
  sequence_name TEXT;
BEGIN
  sequence_name := pg_get_serial_sequence('public.equipment_outages', 'id');
  IF sequence_name IS NOT NULL THEN
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO service_role', sequence_name);
  END IF;
END $$;

COMMIT;

NOTIFY pgrst, 'reload schema';
